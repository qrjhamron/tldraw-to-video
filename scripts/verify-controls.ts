import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
import { openStudio } from './browser'
const session=await openStudio('?lesson=intro')
const {page}=session
try{
 const timeline=page.getByRole('slider',{name:'Timeline'})
 const value=async()=>Number(await timeline.inputValue())
 await page.getByRole('button',{name:'▶ Play',exact:true}).click()
 await page.waitForTimeout(350)
 await page.getByRole('button',{name:'Ⅱ Pause',exact:true}).click()
 const paused=await value();assert.ok(paused>200)
 await page.waitForTimeout(150);assert.equal(await value(),paused)
 await page.getByRole('combobox',{name:'Playback speed'}).selectOption('4')
 await page.getByRole('button',{name:'▶ Play',exact:true}).click()
 await page.waitForTimeout(350)
 await page.getByRole('button',{name:'Ⅱ Pause',exact:true}).click()
 assert.ok(await value()>paused+1000)
 await page.getByTitle('Restart').click()
 assert.equal(await value(),0)
 await timeline.focus();await timeline.press('End');assert.equal(await value(),180000)
 await page.getByRole('button',{name:/Dari sekan ke tangen/}).click()
 assert.equal(await value(),20000)
 const pixels=await page.evaluate(()=>window.studio!.renderFrame(59600))
 await page.setViewportSize({width:1280,height:900})
 await page.evaluate(()=>window.studio!.seek(59600))
 assert.equal(await page.evaluate(()=>window.studio!.renderFrame(59600)),pixels,'Drawing-only export is independent of the viewer size')
 await page.screenshot({path:'output/inspection/application-1280.png'})
 await page.getByRole('button',{name:/Record a whiteboard/}).click()
 assert.equal(await page.evaluate(()=>window.studio!.editor.getInstanceState().isReadonly),false)
 await page.mouse.move(500,400);await page.mouse.down();await page.mouse.move(600,450,{steps:8});await page.mouse.up()
 await page.getByRole('button',{name:'Stop & replay',exact:true}).click()
 assert.equal(await page.evaluate(()=>window.studio!.editor.getInstanceState().isReadonly),true)
 assert.ok(await page.evaluate(()=>window.studio!.recording.events.length)>0)
 await page.locator('input[type=file]').setInputFiles('public/lesson.recording.json')
 await page.waitForFunction(()=>window.studio!.recording.durationMs===180000)
 assert.equal(await value(),0)
 await writeFile('output/controls-validation.json',JSON.stringify({passed:true,tests:['Play/pause/resume','4× speed','Restart','Native timeline End seek','Chapter navigation','Viewport-independent drawing export','Start/stop pointer recording','Import recording'],browserErrors:session.errors},null,2))
 assert.deepEqual(session.errors,[])
 console.log('PASS: playback controls, pointer recording, import and viewport-independent frame export')
}finally{await session.close()}
